#!/usr/bin/env python3
"""Writes app/src/main/kotlin/app/absentmotion/fonts/FontCatalog.kt from Google Fonts' public metadata.

  tools/gen_fonts.py [--count 884] [--input metadata.json] [--out FontCatalog.kt]

Reads https://fonts.google.com/metadata/fonts (about 3 MB; the `)]}'` guard line some copies start with is stripped)
or, with --input, a saved copy. Takes the --count most popular families (Google's own `popularity` rank, 1 = most
popular) that can be previewed: open source, not classed as Symbols, no colour-glyph fonts, at least one script in
SCRIPTS below, at least one weight 100..900. Each family's real variants become the variant codes (weight / 100, plus 10 for the italic cut).
The category and script ids below are this app's own numbering; add new scripts at the end so saved ids stay valid.
Needs only the Python standard library.
"""
import argparse, datetime, json, re, sys, urllib.request
from pathlib import Path

URL = "https://fonts.google.com/metadata/fonts"
OUT = Path(__file__).resolve().parent.parent / "app/src/main/kotlin/app/absentmotion/fonts/FontCatalog.kt"

CATEGORIES = {"Sans Serif": 1, "Serif": 2, "Display": 3, "Handwriting": 4, "Monospace": 5}

SCRIPTS = {
    "arabic": (1, "Arabic"), "armenian": (2, "Armenian"), "bengali": (3, "Bengali"),
    "chinese-hongkong": (4, "Chinese (Hong Kong)"), "chinese-simplified": (5, "Chinese (Simplified)"),
    "chinese-traditional": (6, "Chinese (Traditional)"), "cyrillic": (7, "Cyrillic"), "cyrillic-ext": (8, "Cyrillic Extended"),
    "devanagari": (9, "Devanagari"), "ethiopic": (10, "Ethiopic"), "georgian": (11, "Georgian"), "greek": (12, "Greek"),
    "greek-ext": (13, "Greek Extended"), "gujarati": (14, "Gujarati"), "gurmukhi": (15, "Gurmukhi"), "hebrew": (16, "Hebrew"),
    "japanese": (17, "Japanese"), "kannada": (18, "Kannada"), "khmer": (19, "Khmer"), "korean": (20, "Korean"),
    "lao": (21, "Lao"), "latin": (22, "Latin"), "latin-ext": (23, "Latin Extended"), "malayalam": (24, "Malayalam"),
    "myanmar": (25, "Myanmar"), "oriya": (26, "Oriya"), "sinhala": (27, "Sinhala"), "syriac": (28, "Syriac"),
    "tamil": (29, "Tamil"), "telugu": (30, "Telugu"), "thai": (31, "Thai"), "tibetan": (32, "Tibetan"),
    "vietnamese": (33, "Vietnamese"),
}

NOT_SERVED = {"Roboto Flex"}

def load(source):
    text = Path(source).read_text("utf-8") if source else urllib.request.urlopen(
        urllib.request.Request(URL, headers={"User-Agent": "AbsentMotion-gen_fonts/1.0"}), timeout=60).read().decode("utf-8")
    if text.startswith(")]}'"):
        text = text.split("\n", 1)[1]
    return json.loads(text)["familyMetadataList"]

def variant_codes(font):
    codes = set()
    for key in font["fonts"]:
        weight = int(key.rstrip("i"))
        if weight % 100 == 0 and 100 <= weight <= 900:
            codes.add(weight // 100 + (10 if key.endswith("i") else 0))
    return sorted(codes, key=lambda code: (code % 10, code))

def pick(families, count):
    rows = []
    for font in sorted(families, key=lambda f: f["popularity"]):
        name = font["family"]
        scripts = sorted(SCRIPTS[s][0] for s in font["subsets"] if s in SCRIPTS)
        codes = variant_codes(font)
        if (name not in NOT_SERVED and font["category"] in CATEGORIES and font.get("isOpenSource", True) and not font.get("colorCapabilities")
                and "Symbols" not in font.get("classifications", []) and scripts and codes):
            assert re.fullmatch(r'[^|$"\n\\]+', name), name
            rows.append((name, CATEGORIES[font["category"]], scripts, codes))
        if len(rows) == count:
            break
    return rows

HEADER = '''package app.absentmotion.fonts

/*
 * GENERATED by tools/gen_fonts.py from Google Fonts' public metadata (%(url)s, %(date)s). Do not edit by hand:
 * change the script and run it again. %(families)d families, %(variants)d variants, most popular first (Google's own rank).
 *
 * Category ids (Google's "category"):
%(categories)s
 * Script ids (Google's "subsets"), shown as languages:
%(scripts)s
 * Variant code: weight / 100 (1 = Thin ... 9 = Black), plus 10 for the italic cut (14 = Regular Italic).
 * One line per family: name|category|script ids|variant codes.
 */

/** One font in the catalogue; [category] 100 marks an imported file. */
data class FontEntry(val name: FontName, val category: Int, val languages: Set<Int>)
object FontCatalog {
    val categories = linkedMapOf(%(category_map)s)
    val languages = linkedMapOf(
%(script_map)s)
    val entries: List<FontEntry> by lazy {
        families.trim().lineSequence().flatMap { line ->
            val fields = line.split('|')
            val languages = fields[2].split(',').map { it.toInt() }.toSet()
            fields[3].split(',').map { it.toInt() }.map { variant ->
                FontEntry(FontName("googlefonts", fields[0], variant %% 10 * 100, variant > 9), fields[1].toInt(), languages)
            }
        }.toList()
    }
    private val families = """
%(data)s
"""
}
'''

def wrap(items, indent):
    """Items joined by commas, packed into lines of at most 120 columns (never split inside an item), each starting with indent."""
    lines = [indent]
    for item in items:
        if len(lines[-1] + item) > 118 and lines[-1] != indent:
            lines.append(indent)
        lines[-1] += item + ", "
    return "\n".join(line.rstrip().removesuffix(",") if i == len(lines) - 1 else line.rstrip() for i, line in enumerate(lines))

def main():
    arg = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    arg.add_argument("--count", type=int, default=884)
    arg.add_argument("--input", help="a saved copy of the metadata JSON instead of downloading it")
    arg.add_argument("--out", default=str(OUT))
    args = arg.parse_args()
    rows = pick(load(args.input), args.count)
    if len(rows) < args.count:
        sys.exit(f"only {len(rows)} usable families, wanted {args.count}")
    used = {s for _, _, scripts, _ in rows for s in scripts}
    shown = {name: (i, label) for name, (i, label) in SCRIPTS.items() if i in used}
    categories = {v: k for k, v in CATEGORIES.items()}
    Path(args.out).write_text(HEADER % {
        "url": URL, "date": datetime.date.today().isoformat(), "families": len(rows), "variants": sum(len(r[3]) for r in rows),
        "categories": wrap((f"{i} {n}" for i, n in categories.items()), " *   "),
        "scripts": wrap((f"{i} {label}" for i, label in sorted(shown.values())), " *   "),
        "category_map": ", ".join(f'{i} to "{n}"' for i, n in categories.items()),
        "script_map": wrap((f'{i} to "{label}"' for i, label in sorted(shown.values())), "        ") + "\n    ",
        "data": "\n".join(f"{n}|{c}|{','.join(map(str, s))}|{','.join(map(str, v))}" for n, c, s, v in rows),
    }, "utf-8")
    print(f"{args.out}: {len(rows)} families, {sum(len(r[3]) for r in rows)} variants, {len(shown)} scripts")

if __name__ == "__main__":
    main()
