#!/usr/bin/env python3
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "tools/alight_compat.json"
FOREIGN = ROOT / "shared/assets/effects/foreign.json"
EFFECTS = ROOT / "shared/assets/effects"
PAGE = ROOT / "docs/ALIGHT_COMPATIBILITY.md"
ISSUE = "https://github.com/Comett1225/AbsentMotion/issues/new?template=import_problem.yml"
LABELS = {"same": "Same look", "close": "Very close", "similar": "Similar, not identical", "unmeasured": "Converted, not compared yet", "none": "Not converted yet"}
ORDER = ["same", "close", "similar", "unmeasured", "none"]


def effect_name(key):
    path = EFFECTS / (key + ".json")
    return json.loads(path.read_text(encoding="utf-8")).get("name", key) if path.is_file() else key


def build():
    rows = json.loads(DATA.read_text(encoding="utf-8"))
    foreign = json.loads(FOREIGN.read_text(encoding="utf-8"))
    by_id = {}
    for full, rule in foreign.items():
        for prefix in ("com.alightcreative.effects.", "com.alightcreative."):
            if full.startswith(prefix):
                by_id.setdefault(full[len(prefix):], rule["to"])
                break
    seen = set()
    table = []
    for row in rows:
        if row["id"] in seen:
            continue
        target = by_id.get(row["id"])
        seen.add(row["id"])
        status = row["measured"] if target else "none"
        table.append((ORDER.index(status), row["name"].lower(), row["name"], effect_name(target) if target else "-", LABELS[status]))
    for short, target in by_id.items():
        if short not in seen:
            table.append((ORDER.index("unmeasured"), short.lower(), short, effect_name(target), LABELS["unmeasured"]))
    table.sort()
    counts = {k: sum(1 for t in table if t[4] == LABELS[k]) for k in ORDER}
    lines = [
        "# Alight Motion compatibility",
        "",
        "Which Alight Motion effects and blending modes come across when you import an Alight project, which change, and which are not converted yet. This page is generated by `tools/alight_compat.py` from the import rules in the app.",
        "",
        "## Importing an Alight Motion project",
        "",
        "Export the project from Alight Motion as XML and open it in AbsentMotion. After the import, AbsentMotion shows a report that lists every effect it could not convert, how many layers use it, and any missing media, so nothing is dropped without you knowing.",
        "",
        "## In short",
        "",
        "- **%d** Alight effects look the same and **%d** are very close." % (counts["same"], counts["close"]),
        "- **%d** are converted to a similar effect that does not look identical." % counts["similar"],
        "- **%d** are converted but have not been compared side by side yet." % counts["unmeasured"],
        "- **%d** are not converted yet (mostly very old effect versions, VR and some 3D solids)." % counts["none"],
        "- **Blending modes:** all of Alight's blending modes come across. Multiply and Subtract get their opacity converted so they look the same.",
        "",
        "Something imports wrong? [Send the project as an Import problem](%s): the XML and a screenshot of the same moment in Alight Motion. That is the fastest way to get it fixed." % ISSUE,
        "",
        "## Every Alight effect",
        "",
        "| Alight effect | In AbsentMotion | Result |",
        "|---|---|---|",
    ]
    lines += ["| %s | %s | %s |" % (t[2], t[3], t[4]) for t in table]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description="Writes %s from %s and the effect import rules." % (PAGE.relative_to(ROOT), DATA.relative_to(ROOT)))
    parser.add_argument("--check", action="store_true", help="exit 1 if the page is out of date")
    args = parser.parse_args()
    text = build()
    if args.check:
        if not PAGE.is_file() or PAGE.read_text(encoding="utf-8") != text:
            print("docs/ALIGHT_COMPATIBILITY.md is out of date: run python3 tools/alight_compat.py")
            sys.exit(1)
        return
    PAGE.write_text(text, encoding="utf-8")
    print("wrote %s" % PAGE.relative_to(ROOT))


if __name__ == "__main__":
    main()
